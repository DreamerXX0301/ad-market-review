import assert from "node:assert/strict";
import fs from "node:fs/promises";
import ts from "typescript";
const source = await fs.readFile(new URL("./stockCodeCopy.ts", import.meta.url), "utf8");
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ES2022, target: ts.ScriptTarget.ES2022 } }).outputText;
const { stockCodeCopyValue: value, copyStockCode: copy } = await import("data:text/javascript;base64," + Buffer.from(compiled).toString("base64"));
assert.equal(value("000001", "000001.SZ").value, "000001", "leading zeroes are preserved");
assert.equal(value(undefined, "600519.SH").display, "600519");
assert.equal(value("600519.SH").value, "600519");
assert.equal(value("600519", "600519.SH", "full").value, "600519.SH");
assert.equal(value("600519", undefined, "full").value, null, "never invent an exchange suffix");
assert.equal(value("920001", "920001.BJ").value, "920001");
assert.equal(value("885001.TI").value, null, "sector codes are not stock identifiers");
assert.equal(value("—").value, null);
const writes = [];
assert.equal(await copy("000001", { writeText: async text => writes.push(text) }), "copied");
assert.deepEqual(writes, ["000001"]);
assert.equal(await copy("600519.SH", { writeText: async text => writes.push(text) }), "copied");
assert.equal(await copy("invalid", { writeText: async text => writes.push(text) }), "invalid");
assert.equal(writes.length, 2);
assert.equal(await copy("000001", null), "unavailable");
assert.equal(await copy("000001", { writeText: async () => { throw Error("permission denied"); } }), "failed");
let resolve;
const pending = copy("300001", { writeText: () => new Promise(done => { resolve = done; }) });
let finished = false; pending.then(() => { finished = true; });
await Promise.resolve(); assert.equal(finished, false, "success waits for the clipboard write to resolve");
resolve(); assert.equal(await pending, "copied");
Object.defineProperty(globalThis, "navigator", { configurable: true, value: { get clipboard() { throw Error("insecure access"); } } });
assert.equal(await copy("000001"), "failed", "clipboard access errors also preserve manual-copy fallback");
console.log("Stock code copy: six digits/full distinction, leading zeroes, awaited clipboard and safe unavailable/denied paths passed");
