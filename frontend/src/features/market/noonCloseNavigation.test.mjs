import assert from "node:assert/strict";
import fs from "node:fs/promises";
import ts from "typescript";
const source = await fs.readFile(new URL("./noonCloseNavigation.ts", import.meta.url), "utf8");
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ES2022, target: ts.ScriptTarget.ES2022 } }).outputText;
const { noonCloseChartDate, noonCloseSectorSelection } = await import("data:text/javascript;base64," + Buffer.from(compiled).toString("base64"));
const day = "2026-10-28", published = ["2026-10-27", day, "2026-10-29"];
assert.equal(noonCloseChartDate(published, day, day), day);
for (const request of ["2026-10-27", "2026-10-29", "invalid"]) assert.equal(noonCloseChartDate(published, day, request), null);
assert.equal(noonCloseChartDate(["2026-10-27", "2026-10-29"], day, day), null);
assert.equal(noonCloseChartDate(["2026-02-30"], "2026-02-30", "2026-02-30"), null);
const sector = { topic_code: "884288.TI", instrument_id: "884288.TI", kind: "industry", name: "合成行业" };
const chart = noonCloseSectorSelection(sector, day, published, day);
assert.equal(chart.date, day);
assert.equal(chart.view, "chart");
assert.equal(chart.topic.noon_chart_as_of, day);
assert.match(chart.topic.noon_scope_notice, /不包含后续交易日/);
assert.equal(noonCloseSectorSelection(sector, day, published, day, "members").view, "members");
for (const invalid of [{ ...sector, instrument_id: "884289.TI" }, { ...sector, kind: "stock" }, { name: sector.name, kind: "industry" }]) assert.equal(noonCloseSectorSelection(invalid, day, published, day), null);
assert.equal(noonCloseSectorSelection(sector, day, published, "2026-10-29"), null);
