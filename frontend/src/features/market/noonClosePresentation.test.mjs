import assert from "node:assert/strict";
import fs from "node:fs/promises";
import ts from "typescript";

const input = await fs.readFile(new URL("./noonClosePresentation.ts", import.meta.url), "utf8");
const compiled = ts.transpileModule(input, { compilerOptions: { module: ts.ModuleKind.ES2022, target: ts.ScriptTarget.ES2022 } }).outputText;
const p = await import("data:text/javascript;base64," + Buffer.from(compiled).toString("base64"));
assert.equal(p.closeNumber(0), 0);
assert.equal(p.closeCountTone(0,"down"),"muted");
assert.equal(p.closeCountTone(3,"down"),"down");
for (const value of [null, undefined, "", "0", false, NaN, Infinity]) assert.equal(p.closeNumber(value), null);
assert.equal(p.closeTransitionTone({ transition: "opened", close_state: "not_listed", close_change_pct: 4.2 }), "down", "event feedback is independent from a still-positive day change");
assert.equal(p.closeTransitionTone({ transition: "down_opened", close_state: "not_listed", close_change_pct: -4 }), "up", "opening a limit-down is repair, not an invented positive return");
assert.equal(p.closeTransitionTone({ transition: "resealed", close_state: "conflict" }), "close-warn");
assert.equal(p.closeTransitionLabel({ transition: "resealed", close_state: "limit_up" }), "午间炸板 → 收盘回封");
assert.equal(p.closeStateLabel({ close_state: "limit_up", final_board_count: 5 }), "收盘5连板");
assert.equal(p.closeStateLabel({ close_state: "limit_up", final_board_count: 1 }), "收盘首板");
assert.match(p.closeStateLabel({ close_state: "limit_up", final_board_count: null }), /待核验/);
assert.equal(p.closeDayEventLabel("ever_broken"), "日内曾炸板");
assert.equal(p.closeCopyCodes(["000001.SZ", "000001", "600002.SH", "920003.BJ", "SH600001", "missing", "600002.SH"]), "000001\n600002\n920003");
const options = { date: "2026-10-28", reviewId: "review-fixed", section: "all", board: "star", transition: "resealed", sort: "afternoon_change_pct", direction: "asc", cursor: "cursor+A/B", classification: "industry|fuyao|881001.TI|2026-10-21" };
const parsed = new URL("https://fixture.invalid/api/v1" + p.closeItemsPath(options));
assert.equal(parsed.searchParams.get("review_id"), "review-fixed");
assert.equal(parsed.searchParams.get("classification"), options.classification);
assert.equal(parsed.searchParams.get("cursor"), options.cursor);
assert.equal(parsed.searchParams.get("board"), "star");
const copied = new URL("https://fixture.invalid/api/v1" + p.closeItemsPath({ ...options, codesOnly: true }));
assert.equal(copied.searchParams.get("cursor"), null, "copy covers the complete filtered range, not the current page");
assert.equal(copied.searchParams.get("codes_only"), "true");
assert.equal(copied.searchParams.get("sort"), parsed.searchParams.get("sort"));
assert.deepEqual(p.closeMetric({ count: 0, source_count: 3, denominator: 2, unknown_count: 1, rate_pct: 0 }), { count: 0, source: 3, denominator: 2, unknown: 1, rate: 0 });
assert.deepEqual(p.closeMetric({}), { count: null, source: null, denominator: null, unknown: null, rate: null });
for (const state of ["waiting_close", "not_collected", "no_snapshot", "purged"]) assert.ok(p.closeStateMessages[state]);
assert.equal(p.CLOSE_SECTIONS.length, 6);
console.log("Close review presentation: event/price color separation, missing vs zero, exact revision filters, whole-range six-digit copying and six-section route passed");
