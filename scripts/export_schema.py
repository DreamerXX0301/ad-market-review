#!/usr/bin/env python3
"""Export schema only from repository migrations, never from a user's database.

The generated SQL is an inspection/validation artifact. Runtime databases must
still be initialized by ``python -m app.cli migrate`` so migration checksums are
registered. No provider credentials, settings, rows, or network calls are read.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import sqlite3

ROOT = Path(__file__).resolve().parents[1]
MIGRATIONS = ROOT / "backend/app/migrations"
SQL_PATH = ROOT / "contracts/schema-current.sql"
SUMMARY_PATH = ROOT / "contracts/schema-current.json"
MIGRATION_TABLE = "CREATE TABLE _schema_migration (name TEXT PRIMARY KEY, sha256 TEXT NOT NULL, applied_at_ms INTEGER NOT NULL)"


def connection():
    conn = sqlite3.connect(":memory:")
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys=ON")
    conn.execute("PRAGMA recursive_triggers=ON")
    conn.execute("PRAGMA busy_timeout=10000")
    return conn


def build_schema():
    conn = connection()
    conn.execute(MIGRATION_TABLE)
    migrations = []
    version = 0
    for path in sorted(MIGRATIONS.glob("[0-9]*.sql")):
        content = path.read_bytes()
        sha = hashlib.sha256(content).hexdigest()
        body = "\n".join(
            line for line in content.decode("utf-8").splitlines()
            if not line.strip().upper().startswith("PRAGMA ")
            and line.strip().upper() not in ("BEGIN IMMEDIATE;", "BEGIN;", "COMMIT;")
        )
        try:
            conn.executescript("BEGIN IMMEDIATE;\n" + body + "\nCOMMIT;")
        except BaseException:
            conn.rollback()
            raise
        version = max(version, int(path.name.split("_", 1)[0]))
        migrations.append({"name": path.name, "sha256": sha})
    objects = [dict(row) for row in conn.execute(
        "SELECT type,name,tbl_name,sql FROM sqlite_schema "
        "WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' "
        "ORDER BY CASE type WHEN 'table' THEN 0 WHEN 'index' THEN 1 WHEN 'view' THEN 2 ELSE 3 END,name"
    )]
    header = [
        "-- Generated by scripts/export_schema.py from repository migrations only.",
        "-- Schema reference: no user data, no credentials, no default rows.",
        "-- Do NOT use this as runtime bootstrap/restore; run app.cli migrate instead.",
        "-- Applied migration history is intentionally absent from this artifact.",
        *[f"-- {m['name']} sha256={m['sha256']}" for m in migrations],
        "PRAGMA foreign_keys=ON;", "PRAGMA recursive_triggers=ON;", "BEGIN IMMEDIATE;",
    ]
    sql = "\n".join(header) + "\n\n" + "\n\n".join(
        row["sql"].rstrip(";") + ";" for row in objects
    ) + "\n\nCOMMIT;\n"
    tables = {}
    for row in objects:
        if row['type'] != 'table':
            continue
        name = row['name']
        tables[name] = {
            "columns": [dict(column) for column in conn.execute(f'PRAGMA table_info("{name}")')],
            "foreign_keys": [dict(key) for key in conn.execute(f'PRAGMA foreign_key_list("{name}")')],
            "triggers": [x['name'] for x in objects if x['type'] == 'trigger' and x['tbl_name'] == name],
        }
    summary = {
        "source": "repository migrations applied to disposable in-memory SQLite",
        "runtime_initialization": "python -m app.cli migrate",
        "migration_version": version,
        "migrations": migrations,
        "counts": {kind: sum(row['type'] == kind for row in objects) for kind in ('table', 'index', 'view', 'trigger')},
        "schema_sha256": hashlib.sha256(sql.encode()).hexdigest(),
        "tables": tables,
    }
    replica = connection()
    replica.executescript(sql)
    assert replica.execute("PRAGMA integrity_check").fetchone()[0] == 'ok'
    assert not replica.execute("PRAGMA foreign_key_check").fetchall()
    assert all(replica.execute(f'SELECT count(*) FROM "{name}"').fetchone()[0] == 0 for name in tables)
    recreated = [tuple(row) for row in replica.execute("SELECT type,name,sql FROM sqlite_schema WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY type,name")]
    original = [tuple(row) for row in conn.execute("SELECT type,name,sql FROM sqlite_schema WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY type,name")]
    assert original == recreated, 'export must recreate every explicit schema object exactly'
    replica.close()
    conn.close()
    return sql, summary


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='validate generated files are current, without writing')
    args = parser.parse_args()
    sql, summary = build_schema()
    serialized = json.dumps(summary, ensure_ascii=False, indent=2) + '\n'
    if args.check:
        if SQL_PATH.read_text() != sql or SUMMARY_PATH.read_text() != serialized:
            raise SystemExit('Schema artifacts are stale; run scripts/export_schema.py')
    else:
        SQL_PATH.write_text(sql, encoding='utf-8')
        SUMMARY_PATH.write_text(serialized, encoding='utf-8')
    print(json.dumps({'valid': True, 'sqlite': sqlite3.sqlite_version, 'counts': summary['counts'], 'data_rows_exported': 0, 'schema_sha256': summary['schema_sha256']}, ensure_ascii=False))


if __name__ == '__main__':
    main()
